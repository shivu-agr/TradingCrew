"""Workflow-version stamping (Phase 0 — trust foundation).

Every episode written to disk should carry enough provenance to answer
one question later: *"which version of the workflow produced this
decision?"*.  Proposals generated by a drifting / experimental crew are
not trustworthy for policy evaluation, so the backtest / grid-search /
RLMF paths need to be able to filter to a single stable cohort instead
of blindly trusting the whole append-only history.

We stamp three orthogonal identifiers:

- ``prompts_hash``  — SHA-256 over the agent + task prompt YAML.  Changes
                      the moment any persona / task instruction changes,
                      which is the dominant source of decision-policy drift.
- ``code_git_sha``  — the repo commit (reuses the M6 manifest helper), so a
                      logic change in the deterministic layer is also visible.
- ``workflow_version`` — a compact ``{git8}-{prompts8}`` tag that is cheap to
                      group by in the UI / API.

All three are computed once and cached per process; the config files do
not change mid-run.
"""

from __future__ import annotations

import hashlib
import logging
import os
from pathlib import Path
from typing import List, Optional

logger = logging.getLogger(__name__)

# Prompt config lives next to the crew definition.  Hashing these files
# captures every persona (agents.yaml) + task instruction (tasks.yaml)
# that shapes a decision.
_CONFIG_DIR = Path(__file__).resolve().parent.parent / "config"
_PROMPT_FILES = ("agents.yaml", "tasks.yaml", "run_mode_prompts.yaml")

_prompts_hash_cache: Optional[str] = None
_workflow_version_cache: Optional[str] = None


def _repo_root() -> Path:
    # trading_crew/agentic/versioning.py -> repo root is three levels up.
    return Path(__file__).resolve().parent.parent.parent


def prompts_hash() -> str:
    """SHA-256 (hex) over the prompt YAML files, or ``"unknown"``.

    Deterministic: files are hashed in a fixed order with their bytes
    concatenated under a filename separator so a rename is detectable.
    """
    global _prompts_hash_cache
    if _prompts_hash_cache is not None:
        return _prompts_hash_cache
    h = hashlib.sha256()
    found_any = False
    for name in _PROMPT_FILES:
        p = _CONFIG_DIR / name
        if not p.is_file():
            continue
        found_any = True
        h.update(name.encode("utf-8"))
        h.update(b"\0")
        h.update(p.read_bytes())
        h.update(b"\0")
    _prompts_hash_cache = h.hexdigest() if found_any else "unknown"
    return _prompts_hash_cache


def code_git_sha() -> str:
    """Short git SHA of the working tree (``"unknown"`` outside a checkout)."""
    try:
        from trading_crew.agentic.backtest.manifest import _git_sha

        sha, _dirty = _git_sha(_repo_root())
        return sha
    except Exception:  # noqa: BLE001 — provenance is best-effort, never fatal
        return "unknown"


def workflow_version() -> str:
    """Compact ``{git8}-{prompts8}`` tag used for cohort grouping."""
    global _workflow_version_cache
    if _workflow_version_cache is not None:
        return _workflow_version_cache
    git8 = (code_git_sha() or "unknown")[:8]
    prompts8 = (prompts_hash() or "unknown")[:8]
    _workflow_version_cache = f"{git8}-{prompts8}"
    return _workflow_version_cache


def reset_cache() -> None:
    """Test hook — drop the cached identifiers so the next call re-reads."""
    global _prompts_hash_cache, _workflow_version_cache
    _prompts_hash_cache = None
    _workflow_version_cache = None


def filter_episodes_by_cohort(
    episodes: List,
    *,
    workflow_version: Optional[str] = None,
    prompts_hash: Optional[str] = None,
    source: Optional[str] = None,
):
    """Return the subset of ``episodes`` matching the requested cohort.

    Any argument left ``None`` is not filtered on.  Episodes written
    before Phase 0 (no ``workflow_version`` / ``prompts_hash`` stamp) are
    treated as *not* matching a specific-version request — that is the
    point: untrusted, unstamped history is excluded when you ask for a
    concrete cohort, but included when no cohort is specified.
    """

    def _match(ep) -> bool:
        if workflow_version is not None and getattr(ep, "workflow_version", None) != workflow_version:
            return False
        if prompts_hash is not None and getattr(ep, "prompts_hash", None) != prompts_hash:
            return False
        if source is not None and (getattr(ep, "source", None) or "live") != source:
            return False
        return True

    return [ep for ep in episodes if _match(ep)]


def current_source() -> str:
    """Return the episode ``source`` for the current process.

    Set ``TRADINGCREW_EPISODE_SOURCE=backfill`` in the offline backfill
    harness so its episodes are distinguishable from live runs.  Defaults
    to ``"live"``.
    """
    raw = (os.environ.get("TRADINGCREW_EPISODE_SOURCE") or "live").strip().lower()
    return raw if raw in ("live", "backfill") else "live"
